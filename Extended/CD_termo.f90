module CD_termo

   use global

   implicit none
   private
   public :: CD_termo_run

 contains

   !============================================================================
   ! CD_termo_run
   !============================================================================
   ! This module calculates the thermodynamical quantities along the shock 
   ! coincident with the CD trayectory (curve generated by CD.f90). On one side of 
   ! the CD there is shocked stellar-wind and on the other shocked ISM; we compute 
   ! and save only the quantities of the SSW in termo_sw.dat. It also calculates 
   ! the injected luminosity at each shock segment.
   !___________________________________________________________________________

   subroutine CD_termo_run(shock)

      use global
      !$ use omp_lib
      implicit none
      character(LEN=*), intent(in) :: shock
      real(dp) :: A_z,A_omega,st,ct
      real(dp) :: cte_P,cte_T,cte_rho,cte_ad
      real(dp) :: Beq0,v_sh,H0
      real(dp) :: dOmega,dtheta,dR(m_theta),dA,dV_cell(m_theta)
      real(dp) :: L_inj(m_theta),L_perp,L_inj_tot, L_sh, R_acel(m_theta)
      real(dp) :: v_vec(2), n_perp(2), n_t(2)
      real(dp) :: l_crit
      real(dp) :: dot_M, dM
      allocate( theta(m_theta),r_norm(m_theta),H_norm(m_theta),R_theta(m_theta) )
      allocate( x(m_theta), y(m_theta) )
      allocate( Mach(m_theta),P_th_w(m_theta),C_s_med(m_theta),C_s_sh(m_theta),r(m_theta) )
      allocate( P_med(m_theta), rho_med(m_theta) )
      allocate( P(m_theta),rho(m_theta),T(m_theta),B(m_theta),v_t(m_theta),v_perp(m_theta) )
      allocate( v_t_old(m_theta), P_old(m_theta), rho_old(m_theta))
      allocate( H_new(m_theta), y_eff(m_theta) )

      80    format(A13,X,Es10.2)
      81    format(A18,X,Es10.2)
      82    format(A16,X,Es10.2)
      83    format(A18,X,Es10.2)

      write(*,*) '\n Calculate thermodynamic variables in the shocks'

      !-----------------------------------------------------------------
      !Define some values first
      if (shock == 'RS') then
         v_sh = v_w
         L_sh = L_wind
      else if (shock == 'FS') then
         v_sh = v_ISM
         L_sh = L_ISM
      end if
         
      !-----------------------------------------------------------------
      ! Read the shock position and cell size: theta,r_norm(theta),dR(theta)

      open(11,file='CD.dat')
      do l = 1, m_theta
         read(11,*) theta(l), r_norm(l), dR(l), dummy, R_acel(l)
         R_theta(l) = r_norm(l) * R0
      end do
      close(11)
      dtheta = theta(2)-theta(1)    ! Constant step in theta

      !-----------------------------------------------------------------
      ! Read y coordinate (normalized)

      open(12, file='CD_xy.dat')
      do l= 1, m_theta
         read(12,*) x(l), y(l)
      end do
      close(12)

      !-----------------------------------------------------------------
      ! Calculate the normal and tangential vectors at each position
      ! using Eqs.12-16 from Christie+16; we also calculate H(theta)/R(theta)

      open(18,file='Hnorm_'//shock//'.dat') ! normalized
      do l = 1, m_theta
         st = sin(theta(l))
         ct = cos(theta(l))
         call A_theta(shock,theta(l),st,ct,r_norm(l),A_z,A_omega,H_norm(l))
         if (shock == 'RS') then
            n_perp = (/ -A_omega, -A_z /)! Internal perpendicular vector to the BS surface
            n_t = (/ -A_z, A_omega /)     ! Tangential vector to the BS surface
            v_vec = v_sh * (/ -ct, st /)
            !v_perp(l) = v_sh * ( -st*A_z + ct*A_omega ) !Eq 18
            v_t_old(l) = v_sh * ( ct*A_z + st*A_omega )
         else if (shock == 'FS') then
            n_perp =  (/ A_omega, A_z /) ! External perpendicular vector to the BS surface
            n_t = (/ -A_z, A_omega /)    ! Tangential vector to the BS surface
            v_vec = v_sh * (/1.d0, 0.d0/)
            v_t_old(l) = v_sh*max(-A_z,0.)
         end if
         v_perp(l) = max( DOT_PRODUCT(v_vec,n_perp), 0.d0 )
         !v_t(l) = max( DOT_PRODUCT(v_vec,n_t), 1.d-10 ) ! Just so we don't get a zero value in l=1
         dV_cell(l) = R_theta(l)*sin(theta(l))*dR(l)*(H_norm(l)*R_theta(l)) ! Volume of the cell
         write(18,*) theta(l), H_norm(l)*R_theta(l), R_acel(l)*R0
      end do
      close(18)

      ! particle accel. efficiency at the shock, depending on theta
      allocate( efi_ac_sh(m_theta) )
      open (18,file='efi_ac_'//shock//'.dat')
      do l = 1,m_theta
         efi_ac_sh(l) = 2.d0*pi*(c/v_perp(l))**2
         write(18,*) theta(l), efi_ac_sh(l)
      end do
      close(18)
      deallocate( efi_ac_sh )


      !-----------------------------------------------------------------
      ! Injected power available for acceleration of NT particles
      ! (depends on the energy flux perpendicular to the shock)

      L_inj_tot = 0.d0

      open(42,file='Linj_'//shock//'.dat')            ! stores L_inj in one quadrant
      do l = 1, m_theta      
         if (shock == 'RS') then
            dOmega = sin(theta(l))*dtheta*d_phi 
            L_perp = (Mdot*v_perp(l)**2)/2.d0
            L_inj(l) = L_perp*(dOmega/4.d0/pi)
         else if (shock == 'FS') then
            dA = (d_phi*R_theta(l)*sin(theta(l))) * dR(l)
            L_perp = 0.5*rho_ISM*v_perp(l)**2 * v_sh ! Valentí???? v_perp(l)**3 
            L_inj(l) = L_perp*dA 
         end if
         L_inj_tot = L_inj_tot + L_inj(l)         
         write(42,*) theta(l), r_norm(l), L_inj(l), dR(l)/R0, L_inj_tot*(mphi*4.)/L_sh
      end do
      close(42)

      write(*,80) 'L_inj('//shock//') =', L_inj_tot*(mphi*4.) ! It was just 1 quadrant
      write(*,81) 'L_NT/L_sh('//shock//') [%] =', frac_NT*(L_inj_tot*mphi*4.)/L_sh*100.d0
      if (shock == 'RS') then
         write(*,82) 'L_inj(RS)/L_w =', L_inj_tot*(mphi*4.)/L_sh
      else if (shock == 'FS') then
         write(*,83) 'L_inj(FS)/L_ISM =', L_inj_tot*(mphi*4.)/L_sh
      end if


      !-----------------------------------------------------------------
      !
      !  Thermodynamical quantities (shock)
      !
      !-----------------------------------------------------------------

      ! set omp threads number
      ! $ call omp_set_num_threads(nth)


      cte_P = 2./(g_ad+1.)
      cte_T = ( (g_ad-1.)/(g_ad+1.)**2 ) * (mp/k)
      cte_rho = (g_ad+1.)/(g_ad-1.)*(v_ISM/v_w)**2/(1.-lambda)
      cte_ad = g_ad/(g_ad-1.)

      
      if (shock == 'RS') then
         rho_med(1) = Mdot/(4.d0*pi*R_theta(1)**2*v_w)
         P_th_w(1) = rho_med(1)*k*T_wind/mu_w/mp             ! Stellar wind thermal pressure at R0
         c_s_med(1) = sqrt(g_ad*P_th_w(1)/rho_med(1))       
      else if (shock == 'FS') then
         rho_med(1) = rho_ISM    
         !P(1) = (1.+alpha_ISM)*rho_med*v_sh*v_perp(1)
         C_s_med(1) = sqrt(g_ad*P_th_ISM/rho_med(1))
         !rho(1) = cte_ad*P(1)/( cte_ad*P_th_ISM/rho_med + 0.5*v_sh**2 ) ! cte_ad*P_th_ISM/rho_ISM + 0.5*v_sh**2 = 0.5*v_t(l)**2 + cte_ad*P(l)/rho(l)
      end if
      P(1) = rho_med(1)*v_sh*v_perp(1)
      rho(1) = cte_ad*2*P(1)/v_sh**2            ! 0.5*v_sh**2 = 0.5*v_t(l)**2 + (g_ad/(g_ad-1.))*P(l)/rho(l), v_t(1) = 0.
      P_old(1) = cte_P*rho_med(1)*v_perp(1)**2
      rho_old(1) = (g_ad+1.)/(g_ad-1.)*rho_med(1)
      T(1) = cte_T*v_perp(1)**2
      Mach(1) = v_perp(1)/C_s_med(1)
      r(1) = (g_ad+1.)*Mach(1)**2/((g_ad-1.)*Mach(1)**2+2.)
      Beq0 = sqrt(8.d0*pi*P(1))
      B(1) = frac_sh*Beq0
      C_s_sh(1) = sqrt(g_ad*P(1)/rho(1))
      v_t(1) = 0.d0

      !  $omp parallel do private(l)
      do l = 2, m_theta                                ! Calculo para la mitad de arriba
         if (shock == 'RS') then
            rho_med(l) = Mdot/(4.d0*pi*R_theta(l)**2*v_w)
            P_th_w(l) = rho_med(l)*k*T_wind/mu_w/mp             ! SW thermal pressure at R0
            c_s_med(l) = sqrt(g_ad*P_th_w(l)/rho_med(l))        ! Speed of sound along the stellar wind
         else if (shock == 'FS') then
            c_s_med(l) = sqrt(g_ad*P_th_ISM/rho_med(l))         ! Speed of sound in the ISM
            rho_med(l) = rho_ISM
         end if

         P_old(l) = cte_P*rho_med(l)*v_perp(l)**2
         rho_old(l) = (g_ad+1.)/(g_ad-1.)*rho_med(l)

         Mach(l) = v_perp(l)/C_s_med(l)
         r(l) = (g_ad+1.)*Mach(l)**2/((g_ad-1.)*Mach(l)**2+2.) ! Compression factor (Caprioli 2014, Eq. 1)

         if ( v_t(l-1) <= C_s_sh(l-1) ) then                 ! Check whether the shocked fluid is subsonic or not
             !if (shock == 'RS') then
             P(l) = rho_med(l)*v_sh*v_perp(l) !*r_norm(l)**2
             !else if (shock == 'FS') then
             !P(l) = (1.+alpha_ISM)*rho_med*v_sh*v_perp(l)
             !end if
             l_crit = l                                      ! l for which shocked fluid becomes supersonic
             
         else
             !if (shock == 'RS') then
             P(l) = rho_med(l)*v_perp(l)**2/(v_perp(l_crit)/v_sh)   !*r_norm(l)**2   ! sin(ang0) = v_perp(l_crit)/v_sh
             !else if (shock == 'FS') then
             !P(l) = (1.+alpha_ISM)*rho_med*v_perp(l)**2/(v_perp(l_crit)/v_sh)
             !end if
         end if
         rho(l) = rho(1)*(P(l)/P(1))**(1./g_ad)              ! Adiabatic relation
         C_s_sh(l) = sqrt(g_ad*P(l)/rho(l))                  ! Sound speed in the shocked fluid     
         T(l) = cte_T*v_perp(l)**2                 ! Eq. 20
         Beq0 = sqrt(8.d0*pi*P(l))     ! sqrt(4.d0*pi*rho(l)*v(l)**2.d0)
         ! If U_mag = frac*U_th -> B^2/4pi = frac*(g_ad/g_ad - 1)*P 
         ! If P_mag = frac*P_th -> B^2/8pi = frac*P 
         B(l) = frac_sh*Beq0

         !if (shock == 'RS') then
            ! Kinetic energy p/ unit mass in the upstream region = Kinetic p/ unit mass + specific enthalpy in the downstream region
            v_t(l) = sqrt( 2.d0 * (0.5d0*v_sh**2-cte_ad*P(l)/rho(l)) )
         !else if (shock == 'FS') then
            ! Add ISM specific enthalpy
          !  v_t(l) = sqrt( 2.d0 * (0.5d0*v_sh**2+cte_ad*(P_th_ISM/rho_med - P(l)/rho(l)) ))
         !end if
         
      end do
      !  $omp end parallel do

      
      !------------------------------
      !Calculate injection spectral index at the shocks
      allocate( alpha_sh(m_theta) )
      open(20,file='alpha_'//shock//'.dat')
      do l = 1, m_theta
         alpha_sh(l) = (r(l)+2.d0)/(r(l)-1.d0)
         write(20,*) theta(l),alpha_sh(l)
      end do
      close(20)
      deallocate( alpha_sh )


      !------------------------------
      ! Calculate shock's width

      do l = 1, m_theta
         y_eff(l) = y(l)*R0
      end do
      dot_M = 0.d0

      do l = 1, m_theta
         dM = rho_med(l)*v_perp(l)*2*pi*R_theta(l)*sin(theta(l))*dR(l)
         dot_M = dot_M + dM

         if (theta(l) < 0.25d0) then
            if (shock == 'RS') then
               H_new(l) = 0.25*R_theta(l)
            else if (shock == 'FS') then
               H_new(l) = 0.4*R_theta(l)
            end if
         else   
            H_new(l) = dot_M/(2*pi*y_eff(l)*rho(l)*v_t(l))   ! dot_M = 2*pi*y_eff(l)*H_new(l)*rho(l)*v_t(l)
         end if

      end do
      

      !------------------------------
      ! Write the results

      open(16,file='termo_'//shock//'.dat')
      open(17,file='termonorm_'//shock//'.dat') ! normalized
      open(18, file='new_vs_old_'//shock//'.dat') ! comparison btw P, rho and v_t new vs old
      open(19, file='H_'//shock//'.dat')
      do l = 1, m_theta
         write(16,*) l,rho(l),P(l),v_t(l),T(l),B(l),v_perp(l),theta(l),Mach(l),r(l),rho_med(l)
         write(17,*) theta(l),rho(l)/rho(1),P(l)/P(1),v_t(l)/v_sh,T(l)/T(1),B(l)/B(1),v_perp(l)/v_sh,C_s_sh(l)/v_sh
         write(18,*) theta(l),v_t(l)/v_t_old(l), P(l)/P_old(l), rho(l)/rho_old(l)
         write(19,*) theta(l), H_new(l), H_new(l)/R_theta(l)
      end do
      close(16)
      close(17)
      close(18)
      close(19)

      
      write(*,*) 'At the stagnation point (sw):'
      write(*,41) 'R0[pc] =',R0/pc
      write(*,41) 'R0/Rst =', R0/R_st
      if (shock == 'RS') then
         write(*,41) 'rho0/rho_w =',rho(1)/(Mdot/(4.d0*pi*R0**2*v_w))  
         write(*,41) 'n_a0 =',rho(1)/mp/mu_sw
      else if (shock == 'FS') then
         write(*,41) 'rho0/rho_ISM =',rho(1)/rho_ISM 
         write(*,41) 'n_a0 =',rho(1)/mp/mu_SISM
      end if     
      write(*,41) 'P0 =',P(1)
      write(*,41) 'v0_t =',v_t(1)
      write(*,41) 'T0 =',T(1)
      write(*,41) 'B0 =',B(1)
      write(*,41) 'Beq0 =',sqrt(8.d0*pi*P(1))
      write(*,41) 'B_st <',(B(1)/4.d0)*(R0/R_st)*(v_w/v_st_rot)*r_A_st 
      41  format (A12,ES9.2)

      deallocate( P,rho,T,B,v_t,v_perp,theta,r_norm,H_norm,R_theta,Mach,r,P_med,rho_med,P_th_w,C_s_med,C_s_sh )
      deallocate( x, y, H_new, y_eff )
      deallocate( v_t_old, P_old, rho_old )
      
   END subroutine CD_termo_run

END module CD_termo



!============================================================================

SUBROUTINE A_theta(shock,theta0,st,ct,r1,A_z,A_omega,H0_norm)

   use global
   character(LEN=*), intent(in) :: shock
   real(dp), intent(in) :: theta0,st,ct,r1
   real(dp), intent(out) :: A_z,A_omega,H0_norm
   real(dp) :: f_theta,g_theta

   f_theta = sqrt( (theta0-st*ct)**2*(1.-lambda*r1**2)**2+st**4*(1.-r1**2)**2 ) ! Eq.15

   A_z = st**2*(1.-r1**2)/f_theta ! Eq. 14
   A_omega = (theta0-st*ct)*(1.-lambda*r1**2)/f_theta ! Eq. 13

   g_theta = 2.*(v_ISM/v_w)*(1.-ct) !+ r1**2.*st**2.*(1.-lambda) ! Eq. 22

   if (shock == 'RS') then
      H0_norm = 0.5*(g_ad-1.)/(g_ad+1.) * (v_w/v_ISM)**2* (g_theta**2)/(f_theta*st) ! Eq. 23
      !H0_norm = 0.2d0 ! + (theta0/2./pi)**2.
   else if (shock == 'FS') then
      H0_norm = 0.3
   end if

   RETURN

END SUBROUTINE A_theta


