module CD_termo
   use global
   implicit none

   public :: CD_termo_run

 contains

   !============================================================================
   ! CD_termo_run
   !============================================================================
   ! This module calculates the thermodynamical quantities along the shock 
   ! coincident with the CD trayectory (curve generated by CD.f90). On one side of 
   ! the CD there is shocked stellar-wind and on the other shocked ISM; we compute 
   ! and save only the quantities of the SSW in termo_sw.dat. It also calculates 
   ! the injected luminosity at each shock segment.
   !___________________________________________________________________________

   subroutine CD_termo_run(shock, radiative)
      !$ use omp_lib
      character(LEN=*), intent(in) :: shock
      logical, intent(in) :: radiative
      real(dp) :: A_z,A_omega,st,ct
      real(dp) :: cte_P,cte_T,cte_ad, frac_mu
      real(dp) :: Beq0,Beq0_new,Beq0_RH,v_sh
      real(dp) :: dtheta,dR(m_theta),dV_ring(m_theta),dA_perp
      real(dp) :: L_inj(m_theta), L_inj_tot, L_sh, R_acel(m_theta)
      real(dp) :: v_A_new(m_theta), v_ARH(m_theta), V_A(m_theta)
      real(dp) :: v_vec(2), n_perp(2), n_t(2)
      real(dp) :: e_flux, sin_alpha
      real(dp) :: n_IL(m_theta)
      real(dp) :: dot_M, dM, drho, P_th_med, Omega_in, theta_min, T_med
      real(dp) :: H_ion(m_theta)
      real(dp) :: lambda_tot(m_theta) 
      real(dp) :: t_th(m_theta), t_adv(m_theta), T_IL(l), T_RH(m_theta), T_new(m_theta)
      integer :: l_crit, l_transition, l_min
      logical :: transition
      
      allocate( H_norm(m_theta),H_theta(m_theta),H_1(m_theta) )
      allocate( x(m_theta), y(m_theta) )
      allocate( Mach(m_theta),C_s_med(m_theta),C_s_sh(m_theta),C_s_sh_new(m_theta),r(m_theta) )
      allocate( rho_med(m_theta),rho_IL(m_theta) )
      allocate( P(m_theta),rho(m_theta),T(m_theta),B(m_theta),v_t(m_theta),v_perp(m_theta) )
      allocate( P_new(m_theta),rho_new(m_theta),B_new(m_theta),v_t_new(m_theta) )
      allocate( v_t_RH(m_theta), P_RH(m_theta), rho_RH(m_theta), B_RH(m_theta), rho_min(m_theta) )
      allocate( H_new(m_theta), y_eff(m_theta) )

      80    format(A13,X,Es10.2)
      81    format(A18,X,Es10.2)
      82    format(A16,X,Es10.2)
      83    format(A18,X,Es10.2)

      print *, '\n Calculate thermodynamic variables in the shocks'

      !-----------------------------------------------------------------
      !Define some values first

      if (shock == 'RS') then
         v_sh = v_w
         L_sh = L_wind
         frac_mu = mu_sw/mu_w
      else if (shock == 'FS') then
         v_sh = v_ISM
         L_sh = L_ISM
         frac_mu = mu_SISM/mu_ISM
      end if
         
      !-----------------------------------------------------------------
      ! Read the shock position and cell size: theta,r_norm(theta),dR(theta)

      open(11,file='CD.dat')
      do l = 1, m_theta
         read(11,*) theta(l), r_norm(l), dR(l), dummy, R_acel(l)
      end do
      close(11)
      dtheta = theta(2)-theta(1)    ! Constant step in theta

      !-----------------------------------------------------------------
      ! Read y coordinate (normalized)

      open(12, file='CD_xy.dat')
      do l = 1, m_theta
         read(12,*) x(l), y(l)
      end do
      close(12)

      !-----------------------------------------------------------------
      ! Calculate the normal and tangential vectors at each position
      ! using Eqs.12-16 from Christie+16

      do l = 1, m_theta
         st = sin(theta(l))
         ct = cos(theta(l))
         call A_theta(theta(l),st,ct,r_norm(l),A_z,A_omega)!,shock,H_norm(l))
         if (shock == 'RS') then
            n_perp = (/ -A_omega, -A_z /)! Internal perpendicular vector to the BS surface
            n_t = (/ -A_z, A_omega /)     ! Tangential vector to the BS surface
            v_vec = v_sh * (/ -ct, st /)
            !v_perp(l) = v_sh * ( -st*A_z + ct*A_omega ) !Eq 18
            v_t_RH(l) = v_sh * ( ct*A_z + st*A_omega )
         else if (shock == 'FS') then
            n_perp =  (/ A_omega, A_z /) ! External perpendicular vector to the BS surface
            n_t = (/ -A_z, A_omega /)    ! Tangential vector to the BS surface
            v_vec = v_sh * (/1.d0, 0.d0/)
            v_t_RH(l) = v_sh*max(-A_z,0.)
         end if
         v_perp(l) = max( DOT_PRODUCT(v_vec,n_perp), 0.d0 )
         !v_t(l) = max( DOT_PRODUCT(v_vec,n_t), 1.d-10 ) ! Just so we don't get a zero value in l=1
      end do

      !-----------------------------------------------------------------
      ! particle accel. efficiency at the shock, depending on theta

      allocate( efi_ac_sh(m_theta) )
      open (18,file='efi_ac_'//shock//'.dat')
      do l = 1,m_theta
         efi_ac_sh(l) = 2.d0*pi*(c/v_perp(l))**2
         write(18,*) theta(l), efi_ac_sh(l)
      end do
      close(18)
      deallocate( efi_ac_sh )

      !-----------------------------------------------------------------
      !
      !  Thermodynamical quantities (shock)
      !
      !-----------------------------------------------------------------

      cte_P = 2./(g_ad+1.)
      cte_T = ( (g_ad-1.)/(g_ad+1.)**2 ) * (mp/k)
      cte_ad = g_ad/(g_ad-1.)

      if (shock == 'RS') then
         rho_med(1) = Mdot/(4.d0*pi*R_theta(1)**2*v_w)
         P_th_med = rho_med(1)*k*T_wind/mu_w/mp             ! Stellar wind thermal pressure at R0
         c_s_med(1) = sqrt(g_ad*P_th_med/rho_med(1))
         T_med = T_wind
      else if (shock == 'FS') then
         rho_med(1) = rho_ISM  
         P_th_med = P_th_ISM  
         C_s_med(1) = sqrt(g_ad*P_th_med/rho_med(1))
         T_med = T_ISM
      end if
      
      P_new(1) = rho_med(1) * v_sh * v_perp(1)
      rho_min(1) = rho_med(1)
      rho_new(1) = cte_ad * 2.d0 * P_new(1)/v_sh**2 ! 0.5*v_sh**2 = 0.5*v_t(l)**2 + (g_ad/(g_ad-1.))*P(l)/rho(l), v_t(1) = 0.
      Mach(1) = v_perp(1)/C_s_med(1)
      T_new(1) = P_new(1)*mp*mu_sw/rho_new(1)/k     ! mu_SISM = mu_sw
      Beq0_new = sqrt( 8.d0 * pi * P_new(1) )
      B_new(1) = frac_sh * Beq0_new
      v_A_new(1) = B_new(1) / sqrt(4.d0*pi*rho_new(1)) ! Alfven speed
      C_s_sh_new(1) = sqrt( g_ad * P_new(1)/rho_new(1) )
      v_t(1) = 0.d0

      T_RH(1) = ((g_ad-1.d0)*Mach(1)**2+2.d0)*(2.d0*g_ad*Mach(1)**2-(g_ad-1.d0))*mp*C_s_med(1)**2*frac_mu/g_ad/k/((g_ad+1.d0)**2 * Mach(1)**2)
      r(1) = ( (g_ad+1.) * Mach(1)**2 )/ ((g_ad-1.)*Mach(1)**2 + 2.)
      P_RH(1) = cte_P*rho_med(1)*v_perp(1)**2 - (g_ad-1.)*P_th_med/(g_ad+1.)
      rho_RH(1) = r(1)*rho_med(1)
      Beq0_RH = sqrt( 8.d0 * pi * P_RH(1) )
      B_RH(1) = frac_sh * Beq0_RH
      v_ARH(1) = B_RH(1) / sqrt(4.d0*pi*rho_RH(1)) ! Alfven speed

      transition = .true. 
      do l = 2, m_theta                                ! Calculo para la mitad de arriba
         if (shock == 'RS') then
            rho_med(l) = Mdot/(4.d0*pi*R_theta(l)**2*v_w)
            P_th_med = rho_med(l)*k*T_wind/mu_w/mp             ! SW thermal pressure at R0
            c_s_med(l) = sqrt(g_ad*P_th_med/rho_med(l))        ! Speed of sound along the stellar wind
            T_med = T_wind
         else if (shock == 'FS') then
            rho_med(l) = rho_ISM
            c_s_med(l) = sqrt(g_ad*P_th_med/rho_med(l))         ! Speed of sound in the ISM
            T_med = T_ISM
         end if
         
         if ( v_t_new(l-1) <= C_s_sh_new(l-1) ) then                 ! Check whether the shocked fluid is subsonic or not
            P_new(l) = rho_med(l)*v_sh*v_perp(l) !*r_norm(l)**2
            l_crit = l                                      ! l for which shocked fluid becomes supersonic           
         else
            P_new(l) = rho_med(l)*v_perp(l)**2/(v_perp(l_crit)/v_sh)   !*r_norm(l)**2   ! sin(ang0) = v_perp(l_crit)/v_sh
         end if
         
         !if (P_new(l) < 2.d0 * P_th_med) then
         !   print*, '\n ABORT'
         !   print*, 'The ambient medium pressure is too high at position l=',l 
         !   stop
         !endif

         if (shock == 'RS') then
            Omega_in = 2.d0*( 1.d0-cos(pi-theta(l)) ) ! Solid angle of the inner region (divided by pi)
            rho_min(l) = (4.d0-Omega_in)/Omega_in * rho_med(l)
         else if (shock == 'FS') then
            rho_min(l) = rho_med(l)
         end if

         if (transition) then
            rho_new(l) = rho_new(1)*(P_new(l)/P_new(1))**(1.d0/g_ad)       ! Adiabatic relation
            if ( rho_new(l) < 1.1d0 * rho_min(l)) then
               transition = .false.
               l_transition = l 
               print *, 'theta_transition [deg] = ', theta(l)*180./pi
               print *, 'l_transition = ', l_transition  
            end if
         else 
            drho = (rho_min(l)/rho_new(l-1))**(1.d0/float(m_theta-l_transition))
            rho_new(l) = rho_new(l-1)*drho
            !rho(l) = rho(1)*(P(l)/P(1))**(1.d0/g_ad)       ! Adiabatic relation
            !print*,rho(l)/(rho(1)*(P(l)/P(1))**(1.d0/g_ad))       
         endif

         C_s_sh_new(l) = sqrt(g_ad*P_new(l)/rho_new(l))           ! Sound speed in the shocked fluid 
         T_new(l) = P_new(l)*mp*mu_sw/rho_new(l)/k     ! mu_SISM = mu_sw    
         Mach(l) = v_perp(l)/C_s_med(l)

         ! Kinetic energy p/ unit mass in the upstream region = Kinetic p/ unit mass + specific enthalpy in the downstream region
         v_t_new(l) = sqrt( 2.d0 * (0.5d0*v_sh**2-cte_ad*P_new(l)/rho_new(l)) )

         ! If U_mag = frac*U_th -> B^2/4pi = frac*(g_ad/g_ad - 1)*P 
         ! If P_mag = frac*P_th -> B^2/8pi = frac*P 
         Beq0_new = sqrt(8.d0*pi*P_new(l))     ! sqrt(4.d0*pi*rho(l)*v(l)**2)
         if ( v_t_new(l-1) <= C_s_sh_new(l-1) ) then
            B_new(l) = frac_sh*Beq0_new
         else       
            B_new(l) = B_new(l-1)*sqrt(rho_new(l)*v_t_new(l-1)/rho_new(l-1)/v_t_new(l))   ! Frozen-in conditions
         end if
         v_A_new(l) = B_new(l) / sqrt(4.d0*pi*rho_new(l)) ! Alfven speed

         r(l) = (g_ad+1.)*Mach(l)**2/((g_ad-1.)*Mach(l)**2+2.) ! Compression factor (Caprioli 2014, Eq. 1)

         T_RH(l) = ((g_ad-1.d0)*Mach(l)**2+2.d0)*(2.d0*g_ad*Mach(l)**2-(g_ad-1.d0))*mp*C_s_med(l)**2/g_ad/k/((g_ad+1.d0)**2 * Mach(l)**2)
         P_RH(l) = cte_P * rho_med(l) * v_perp(l)**2 - (g_ad-1.)*P_th_med/(g_ad+1.)
         rho_RH(l) = r(l) * rho_med(l)
         Beq0_RH = sqrt( 8.d0 * pi * P_RH(l) )
         B_RH(l) = frac_sh * Beq0_RH
         v_ARH(l) = B_RH(l) / sqrt(4.d0*pi*rho_RH(l)) ! Alfven speed

         !print *, r(l), r(l)/(1.d0 + r(l)*v_A(l)/v_sh)
      end do

      if (radiative) then
         do l = 1, m_theta
            rho(l) = rho_RH(l)
            P(l) = P_RH(l)
            v_t(l) = v_t_RH(l)
            B(l) = B_RH(l)
            C_s_sh(l) = sqrt(g_ad*P_RH(l)/rho_RH(l))
            V_A(l) = v_ARH(l)
            T(l) = T_RH(l)
            if (T(l) < 8.d3) then
               T(l) = 8.d3
            end if
         end do
      else if (.not. radiative) then
         do l = 1, m_theta
            rho(l) = rho_new(l)
            P(l) = P_new(l)
            v_t(l) = v_t_new(l)
            B(l) = B_new(l) 
            C_s_sh(l) = C_s_sh_new(l)
            v_A(l) = v_A_new(l)
            T(l) = T_new(l)
         enddo
      end if

      !-----------------------------------------------------------------
      ! Thermal Bremsstrahlung losses
      open(43,file='t_th_'//shock//'.dat')

      do l=1,m_theta
         if (T(l) < 1.d4) then
            lambda_tot(l) = 4.d-29 * T(l)**0.8     ! GER
         else if ((1.d4 <= T(l)) .AND. (T(l) <= 1.d5)) then    ! Myasnikov+ 1998
            lambda_tot(l) = 7.d-27 * T(l)
         else if ((1.d5 < T(l)) .AND. (T(l) <= 4.d7)) then
            lambda_tot(l) = 7.d-19 * T(l)**(-0.6) 
         else if (T(l) > 4.d7) then
            lambda_tot(l) = 3.d-27 * sqrt(T(l))
         end if

         if (shock == 'RS') then
            t_th(l) = k*T(l)/(r(l) * rho_med(l)/(mu_w * mp) * lambda_tot(l) )/(g_ad-1.d0) ! Thermal losses
         else if (shock == 'FS') then
            t_th(l) = k*T(l)/( r(l) * n_ISM * lambda_tot(l) )/(g_ad-1.d0)
         end if
         write(43,*) theta(l), t_th(l)
      end do

      close(43)

      !-----------------------------------------------------------------
      ! Advection timescale
      open(44,file='t_conv_'//shock//'.dat')

      do l=1,m_theta
         t_adv(l) = R_theta(l)/v_t(l)
         write(44,*) theta(l), t_adv(l)
      end do

      close(44)


      open(66,file='rad_adi_'//shock//'.dat')
      do l=1,m_theta
         write(66,*) theta(l),t_th(l)/t_adv(l)
      end do

      !-----------------------------------------------------------------
      ! Minimum gas temperature
      if (radiative) then
         open(45,file='T_IL_'//shock//'.dat')

         T_IL(1) = (t_th(1)/t_adv(2))*T(l)
         if (T_IL(1) < T_ISM) then
            T_IL(1) = T_ISM
         end if
         rho_IL(1) = rho(1)*(T(1)/T_IL(1))
         n_IL(1) = rho_IL(1)/mp/mu_ISM
         do l=2,m_theta
            T_IL(l) = (t_th(l)/t_adv(l))*T(l)
            if (T(l) <= T_IL(l)) then
               T_IL(l) = T(l)
            else if (T_IL(l) < T_ISM) then
               T_IL(l) = T_ISM
            end if
            rho_IL(l) = rho(l)*(T(l)/T_IL(l))
            n_IL(l) = rho_IL(l)/mp/mu_ISM
         end do
         do l=1,m_theta
            write(45,*) theta(l), T_IL(l)
         end do

         close(45)
      end if

   !-----------------------------------------------------------------
      ! Calculate shock's width

      do l = 1, m_theta
         y_eff(l) = y(l)*R0
      end do

      ! -------------------------------------
      ! Post shock layer of a radiative shock
      if (radiative) then
         do l=1,m_theta
            H_1(l) = (v_perp(l)/r(l))*t_th(l)
         end do
      end if

      dot_M = 0.d0
      theta_min = 0.1d0 ! For theta < theta_min, the approximation is not good
      l_min = int( (theta_min/theta_max) * m_theta )
      do l = 1, m_theta
         ! Calculate the perpendicular area of a ring:
         sin_alpha = v_perp(l)/v_sh
         dA_perp = (R_theta(l)*sin(theta(l))) * (dR(l)*sin_alpha) * 2.d0*pi
         dM = (rho_med(l) * v_sh) * dA_perp
         !dM = rho_med(l)*v_perp(l)*2.*pi*R_theta(l)*sin(theta(l))*dR(l)
         dot_M = dot_M + dM
         if (.not. radiative) then
            H_theta(l) = dot_M/(2.*pi*y_eff(l)*rho(l)*v_t(l))   ! dot_M = 2*pi*y_eff(l)*H(l)*rho(l)*v_t(l)
         else if (radiative) then
            H_theta(l) = frac_H * dot_M/(2.*pi*y_eff(l)*v_t(l)*rho_IL(l)) - H_1(l)*rho(l)/rho_IL(l)
         end if
      end do

      ! For theta < theta_min, we use the value obtained at theta_min
      do l = 1, l_min
         H_theta(l) = H_theta(l_min)
      end do

      !if (radiative) then
      !do l=1,m_theta
      !   print*, H_theta(l)/R_theta(l), H_1(l)/R_theta(l), (H_theta(l)+H_1(l))/R_theta(l)
      !end do
      !end if

      open(21,file='Hnorm_'//shock//'.dat') ! normalized
      do l = 1, m_theta
         st = sin(theta(l))
         dV_ring(l) = (2.d0*pi*R_theta(l)*st) * dR(l) * H_theta(l) ! Volume of the ring
         if ( .not. radiative ) then
            write(21,*) theta(l), H_theta(l), R_acel(l)*R0, H_theta(l)/R_theta(l), dV_ring(l)
         else if (radiative) then
            write(21,*) theta(l), H_theta(l), R_acel(l)*R0, H_theta(l)/R_theta(l), dV_ring(l), H_1(l)
         end if
      end do
      close(21)

      !-----------------------------------------------------------------
      ! Injected power available for the acceleration of NT particles 
      ! The injected power is the energy flux * area_perpendicular

      open(42,file='Linj_'//shock//'.dat')            ! stores L_inj in one quadrant

      L_inj_tot = 0.d0
      do l = 1, m_theta
         ! Calculate the perpendicular area:
         sin_alpha = v_perp(l)/v_sh
         dA_perp = (R_theta(l)*sin(theta(l))) * (dR(l)*sin_alpha) * d_phi

         ! Calculate the energy flux (depends on the sub/super-sonic regime):
         if (.not. radiative ) then
            if (l <= l_crit) then   
               e_flux = 0.5d0 * rho_med(l) * v_sh**3
            else 
               e_flux = 0.5d0 * rho_med(l) * v_sh**2 * v_perp(l)
            endif
         else if (radiative) then
            e_flux = 0.5d0 * rho_med(l) * v_sh**2 * v_perp(l)
         end if

         L_inj(l) = e_flux * dA_perp
         L_inj_tot = L_inj_tot + L_inj(l)         
         write(42,*) theta(l), r_norm(l), L_inj(l), dR(l)/R0, L_inj_tot*(mphi*4.)/L_sh
      end do
      close(42)

      write(*,80) 'L_inj('//shock//') =', L_inj_tot*(mphi*4.) ! It was just 1 quadrant
      write(*,81) 'L_NT/L_sh('//shock//') [%] =', frac_NT*(L_inj_tot*mphi*4.)/L_sh*100.d0
      if (shock == 'RS') then
         write(*,82) 'L_inj(RS)/L_w =', L_inj_tot*(mphi*4.)/L_sh
      else if (shock == 'FS') then
         write(*,83) 'L_inj(FS)/L_ISM =', L_inj_tot*(mphi*4.)/L_sh
      end if
      
      !------------------------------
      !Calculate injection spectral index at the shocks

      allocate( alpha_sh(m_theta) )
      open(20,file='alpha_'//shock//'.dat')
      do l = 1, m_theta
         alpha_sh(l) = 2.2_dp   ! Value used for BD+43°3654
         !alpha_sh(l) = (r(l)+2.d0)/(r(l)-1.d0)
         !dummy = r(l)/(1.d0 + r(l)*v_A(l)/v_sh)         
         !print *, r(l), r(l)/(1.d0 + r(l)*v_ARH(l)/v_sh)
         !print *, alpha_sh(l), (dummy+2.d0)/(dummy-1.d0)
         write(20,*) theta(l),alpha_sh(l)
      end do
      close(20)
      deallocate( alpha_sh )

      !------------------------------
      ! Write the results

      open(16,file='termo_'//shock//'.dat')
      open(17,file='termonorm_'//shock//'.dat') ! normalized
      open(18, file='new_vs_RH_'//shock//'.dat') ! comparison btw P, rho and v_t new vs old
      open(19, file='H_'//shock//'.dat')
      do l = 1, m_theta
         write(16,*) l,rho(l),P(l),v_t(l),T(l),B(l),v_perp(l),theta(l),Mach(l),r(l),rho_med(l),rho_IL(l)
         write(17,*) theta(l),rho(l)/rho(1),P(l)/P(1),v_t(l)/v_sh,T(l)/T(1),B(l)/B(1),v_perp(l)/v_sh,C_s_sh(l)/v_sh,rho_IL(l)/rho_IL(1)
         write(18,*) theta(l),v_t(l)/v_t_RH(l), P(l)/P_RH(l), rho(l)/rho_RH(l)
         if (.not. radiative) then
            write(19,*) theta(l), H_theta(l), H_theta(l)/R_theta(l)
         else if (radiative) then
            write(19,*) theta(l), H_theta(l), H_theta(l)/R_theta(l), H_1(l)/R_theta(l)
         end if
      end do
      close(16)
      close(17)
      close(18)
      close(19)

      if (radiative) then
         open(22, file='termo_radiative_norm.dat')
         do l = 1, m_theta
            write(22,*) theta(l), rho(l)/rho_med(l), rho_IL(l)/rho_med(l), T(l)/T_ISM
         end do
      end if

      print *, 'At the stagnation point (sw):'
      write(*,41) 'R0[pc] =',R0/pc
      write(*,41) 'R0/Rst =', R0/R_st
      if (shock == 'RS') then
         write(*,41) 'rho0/rho_w =',rho(1)/(Mdot/(4.d0*pi*R0**2*v_w))  
         write(*,41) 'n_a0 =',rho(1)/mp/mu_sw
      else if (shock == 'FS') then
         write(*,41) 'rho0/rho_ISM =',rho(1)/rho_ISM 
         write(*,41) 'n_a0 =',rho(1)/mp/mu_ISM
      end if     
      write(*,41) 'P0 =',P(1)
      write(*,41) 'v0_t =',v_t(1)
      write(*,41) 'T0 =',T(1)
      write(*,41) 'B0 =',B(1)
      write(*,41) 'Beq0 =',sqrt(8.d0*pi*P(1))
