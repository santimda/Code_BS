module CD_termo
   use global
   implicit none

   private
   public :: CD_termo_run

 contains

   !============================================================================
   ! CD_termo_run
   !============================================================================
   ! Thermodynamical quantities along the shock (RS or FS), coincident with the
   ! CD (curve generated by CD.f90), and injected luminosity at each shock
   ! segment (Martinez et al. 2022, 2023).
   !  - Adiabatic shock (radiative = .false.): total pressure conversion in the
   !    subsonic region and perpendicular momentum flux in the supersonic one,
   !    polytropic density and Bernoulli for v_t.
   !  - Radiative shock (radiative = .true.): Rankine-Hugoniot jump conditions
   !    (hot layer) plus an isothermal layer (IL).
   ! Main output: termo_<shock>.dat, Hnorm_<shock>.dat, Linj_<shock>.dat
   !============================================================================

   subroutine CD_termo_run(shock, radiative)
      character(LEN=*), intent(in) :: shock
      logical, intent(in) :: radiative
      real(dp) :: A_z, A_omega, st, ct
      real(dp) :: cte_P, cte_ad
      real(dp) :: Beq0_new, Beq0_RH, v_sh
      real(dp) :: L_inj_tot, L_sh
      real(dp) :: v_vec(2), n_perp(2), n_t(2)
      real(dp) :: drho, P_th_med, Omega_in, theta_min, T_med
      real(dp), allocatable :: dR(:), dV_ring(:), R_acel(:)
      real(dp), allocatable :: L_inj(:), L_cum(:), e_flux(:), dA_perp(:), dM(:), dot_M(:)
      real(dp), allocatable :: v_A_new(:), v_ARH(:), V_A(:)
      real(dp), allocatable :: lambda_tot(:), t_th(:), t_adv(:), t_ratio(:)
      real(dp), allocatable :: T_IL(:), T_RH(:), T_new(:)
      integer  :: l_crit, l_transition, l_min, n_adi
      integer  :: iu, iu_n, iu_termo, iu_norm, iu_cmp, iu_H
      logical  :: transition

      allocate( H_theta(m_theta),H_1(m_theta) )
      allocate( x(m_theta), y(m_theta) )
      allocate( Mach(m_theta),C_s_med(m_theta),C_s_sh(m_theta),C_s_sh_new(m_theta),r(m_theta) )
      allocate( rho_med(m_theta),rho_IL(m_theta) )
      allocate( P(m_theta),rho(m_theta),T(m_theta),B(m_theta),v_t(m_theta),v_perp(m_theta) )
      allocate( P_new(m_theta),rho_new(m_theta),B_new(m_theta),v_t_new(m_theta) )
      allocate( v_t_RH(m_theta), P_RH(m_theta), rho_RH(m_theta), B_RH(m_theta), rho_min(m_theta) )
      allocate( y_eff(m_theta) )
      allocate( dR(m_theta), dV_ring(m_theta), R_acel(m_theta) )
      allocate( L_inj(m_theta), L_cum(m_theta), e_flux(m_theta), dA_perp(m_theta), dM(m_theta), dot_M(m_theta) )
      allocate( v_A_new(m_theta), v_ARH(m_theta), V_A(m_theta) )
      allocate( lambda_tot(m_theta), t_th(m_theta), t_adv(m_theta), t_ratio(m_theta) )
      allocate( T_IL(m_theta), T_RH(m_theta), T_new(m_theta) )

      80    format(A13,X,Es10.2)
      81    format(A18,X,Es10.2)
      82    format(A16,X,Es10.2)
      83    format(A18,X,Es10.2)

      call validate_shock(shock, 'CD_termo_run')
      print *, '\n Calculate thermodynamic variables in the shocks'

      !-----------------------------------------------------------------
      !Define some values first

      if (shock == 'RS') then
         v_sh = v_w
         L_sh = L_wind
      else
         v_sh = v_ISM
         L_sh = L_ISM
      end if

      !-----------------------------------------------------------------
      ! Read the shock position and cell size: theta, r_norm(theta), dR(theta)
      ! and the (normalized) cartesian coordinates

      open(newunit=iu, file=output_file('CD.dat'))
      read(iu,*) (theta(l), r_norm(l), dR(l), dummy, R_acel(l), l=1,m_theta)
      close(iu)

      open(newunit=iu, file=output_file('CD_xy.dat'))
      read(iu,*) (x(l), y(l), l=1,m_theta)
      close(iu)

      !-----------------------------------------------------------------
      ! Calculate the normal and tangential vectors at each position
      ! using Eqs.12-16 from Christie+16
      if (shock == 'FS') open(newunit=iu_n, file=output_file('n.dat'))

      do l = 1, m_theta
         st = sin(theta(l))
         ct = cos(theta(l))
         call A_theta(theta(l),st,ct,r_norm(l),A_z,A_omega)
         if (shock == 'RS') then
            n_perp = (/ -A_omega, -A_z /)  ! Internal perpendicular vector to the BS surface
            n_t = (/ -A_z, A_omega /)      ! Tangential vector to the BS surface
            v_vec = v_sh * (/ -ct, st /)
            v_t_RH(l) = v_sh * ( ct*A_z + st*A_omega )
         else
            n_perp =  (/ A_omega, A_z /)   ! External perpendicular vector to the BS surface
            n_t = (/ -A_z, A_omega /)      ! Tangential vector to the BS surface
            v_vec = v_sh * (/1.d0, 0.d0/)
            v_t_RH(l) = v_sh*max(-A_z,0.d0)
            write(iu_n,*) n_t, n_perp
         end if
         v_perp(l) = max( DOT_PRODUCT(v_vec,n_perp), 0.d0 )
      end do

      if (shock == 'FS') close(iu_n)

      v_t_RH(1) = max(v_t_RH(1), 1.d-30*v_sh)   ! formally 0 at the apex

      !-----------------------------------------------------------------
      ! particle accel. efficiency at the shock, depending on theta

      allocate( efi_ac_sh(m_theta) )
      efi_ac_sh = 2.d0*pi*(c/v_perp)**2
      open(newunit=iu, file=output_file('efi_ac_'//shock//'.dat'))
      write(iu,'(2es17.8e3)') (theta(l), efi_ac_sh(l), l=1,m_theta)
      close(iu)
      deallocate( efi_ac_sh )

      !-----------------------------------------------------------------
      !
      !  Thermodynamical quantities (shock)
      !
      !-----------------------------------------------------------------

      cte_P = 2.d0/(g_ad+1.d0)
      cte_ad = g_ad/(g_ad-1.d0)

      if (shock == 'RS') then
         rho_med(1) = Mdot/(4.d0*pi*R_theta(1)**2*v_w)
         P_th_med = rho_med(1)*k*T_wind/mu_w/mp             ! Stellar wind thermal pressure at R0
         T_med = T_wind
      else
         rho_med(1) = rho_ISM
         P_th_med = P_th_ISM
         T_med = T_ISM
      end if
      C_s_med(1) = sqrt(g_ad*P_th_med/rho_med(1))

      ! Adiabatic shock, apex: P = total upstream pressure, rho from Bernoulli (v_t = 0)
      P_new(1) = rho_med(1) * v_sh * v_perp(1)
      rho_min(1) = rho_med(1)
      rho_new(1) = cte_ad * 2.d0 * P_new(1)/v_sh**2 ! 0.5*v_sh**2 = 0.5*v_t(l)**2 + (g_ad/(g_ad-1.))*P(l)/rho(l), v_t(1) = 0.
      Mach(1) = v_perp(1)/C_s_med(1)
      T_new(1) = P_new(1)*mp*mu/rho_new(1)/k     ! mu_SISM = mu
      Beq0_new = sqrt( 8.d0 * pi * P_new(1) )
      B_new(1) = frac_sh * Beq0_new
      v_A_new(1) = B_new(1) / sqrt(4.d0*pi*rho_new(1)) ! Alfven speed
      C_s_sh_new(1) = sqrt( g_ad * P_new(1)/rho_new(1) )
      v_t_new(1) = 1.d-30*v_sh   ! formally 0; avoids divisions by zero (t_adv = R/v_t)

      ! Radiative shock, apex: Rankine-Hugoniot
      if (Mach(1) > 1.d0) then
         r(1) = (g_ad+1.d0)*Mach(1)**2/((g_ad-1.d0)*Mach(1)**2+2.d0)
         T_RH(1) = ((g_ad-1.d0)*Mach(1)**2+2.d0)*(2.d0*g_ad*Mach(1)**2-(g_ad-1.d0))/((g_ad+1.d0)**2*Mach(1)**2) * T_med
         P_RH(1) = cte_P * rho_med(1) * v_perp(1)**2 - (g_ad-1.d0)*P_th_med/(g_ad+1.d0)
      else       ! no shock: upstream values
         r(1) = 1.d0
         T_RH(1) = T_med
         P_RH(1) = P_th_med
      end if
      rho_RH(1) = r(1)*rho_med(1)
      Beq0_RH = sqrt( 8.d0 * pi * P_RH(1) )
      B_RH(1) = frac_sh * Beq0_RH
      v_ARH(1) = B_RH(1) / sqrt(4.d0*pi*rho_RH(1)) ! Alfven speed

      transition = .true.
      l_crit = 1
      do l = 2, m_theta                                ! Upper half
         if (shock == 'RS') then
            rho_med(l) = Mdot/(4.d0*pi*R_theta(l)**2*v_w)
            P_th_med = rho_med(l)*k*T_wind/mu_w/mp             ! SW thermal pressure at R(theta)
         else
            rho_med(l) = rho_ISM
         end if
         C_s_med(l) = sqrt(g_ad*P_th_med/rho_med(l))           ! Speed of sound upstream

         ! Pressure: Eq. 6 (subsonic) and Eq. 7 (supersonic) from Martinez et al. 2022
         if ( v_t_new(l-1) <= C_s_sh_new(l-1) ) then           ! Check whether the shocked fluid is subsonic or not
            P_new(l) = rho_med(l)*v_sh*v_perp(l)
            l_crit = l                                         ! last subsonic position
         else
            P_new(l) = rho_med(l)*v_perp(l)**2/(v_perp(l_crit)/v_sh)   ! sin(ang0) = v_perp(l_crit)/v_sh
         end if

         ! Minimum density: Eq. 9 from Martinez et al. 2022
         if (shock == 'RS') then
            Omega_in = 2.d0*( 1.d0-cos(pi-theta(l)) )          ! Solid angle of the inner region (divided by pi)
            rho_min(l) = (4.d0-Omega_in)/Omega_in * rho_med(l)
         else
            rho_min(l) = rho_med(l)
         end if

         if (transition) then
            rho_new(l) = rho_new(1)*(P_new(l)/P_new(1))**(1.d0/g_ad)       ! Adiabatic relation (Eq. 8)
            if ( rho_new(l) < 1.1d0 * rho_min(l)) then
               transition = .false.
               l_transition = l
               print *, 'theta_transition [deg] = ', theta(l)*180./pi
               print *, 'l_transition = ', l_transition
            end if
         else
            drho = (rho_min(l)/rho_new(l-1))**(1.d0/real(m_theta-l_transition,dp))
            rho_new(l) = rho_new(l-1)*drho
         endif

         C_s_sh_new(l) = sqrt(g_ad*P_new(l)/rho_new(l))           ! Sound speed in the shocked fluid
         T_new(l) = P_new(l)*mp*mu/rho_new(l)/k                   ! mu_SISM = mu
         Mach(l) = v_perp(l)/C_s_med(l)

         ! Bernoulli: kinetic energy p/ unit mass upstream = kinetic + specific enthalpy downstream
         v_t_new(l) = sqrt( 2.d0 * (0.5d0*v_sh**2-cte_ad*P_new(l)/rho_new(l)) )

         ! P_mag = frac*P_th -> B^2/8pi = frac*P (subsonic); frozen-in field (supersonic)
         Beq0_new = sqrt(8.d0*pi*P_new(l))
         if ( v_t_new(l-1) <= C_s_sh_new(l-1) ) then
            B_new(l) = frac_sh*Beq0_new
         else
            B_new(l) = B_new(l-1)*sqrt(rho_new(l)*v_t_new(l-1)/rho_new(l-1)/v_t_new(l))
         end if
         v_A_new(l) = B_new(l) / sqrt(4.d0*pi*rho_new(l)) ! Alfven speed

         ! Rankine-Hugoniot
         if (Mach(l) > 1.d0) then
            r(l) = (g_ad+1.d0)*Mach(l)**2/((g_ad-1.d0)*Mach(l)**2+2.d0)
            T_RH(l) = ((g_ad-1.d0)*Mach(l)**2+2.d0)*(2.d0*g_ad*Mach(l)**2-(g_ad-1.d0))/((g_ad+1.d0)**2*Mach(l)**2) * T_med
            P_RH(l) = cte_P * rho_med(l) * v_perp(l)**2 - (g_ad-1.d0)*P_th_med/(g_ad+1.d0)
         else       ! no shock: upstream values
            r(l) = 1.d0
            T_RH(l) = T_med
            P_RH(l) = P_th_med
         end if
         rho_RH(l) = r(l) * rho_med(l)
         Beq0_RH = sqrt( 8.d0 * pi * P_RH(l) )
         B_RH(l) = frac_sh * Beq0_RH
         v_ARH(l) = B_RH(l) / sqrt(4.d0*pi*rho_RH(l)) ! Alfven speed
      end do

      ! Apex cell: v_t ~ theta near the stagnation point (v_t(1) = 0 only exactly at theta = 0)
      ! Just to avoid numerical errors
      v_t_new(1) = v_t_new(2)*theta(1)/theta(2)
      v_t_RH(1)  = v_t_RH(2)*theta(1)/theta(2)

      if (radiative) then
         rho    = rho_RH
         P      = P_RH
         v_t    = v_t_RH
         B      = B_RH
         C_s_sh = sqrt(g_ad*P_RH/rho_RH)
         V_A    = v_ARH
         T      = max(T_RH, 8.d3)
      else
         rho    = rho_new
         P      = P_new
         v_t    = v_t_new
         B      = B_new
         C_s_sh = C_s_sh_new
         V_A    = v_A_new
         T      = T_new
         rho_IL = rho_new          ! no isothermal layer in an adiabatic shock
      end if

      !-----------------------------------------------------------------
      ! Thermal losses and advection timescales

      lambda_tot = lambda_cool(T)
      if (shock == 'RS') then
         t_th = k*T/(r * rho_med/(mu_w*mp) * lambda_tot)/(g_ad-1.d0)
      else
         t_th = k*T/(r * n_ISM * lambda_tot)/(g_ad-1.d0)
      end if
      t_adv = R_theta/v_t

      open(newunit=iu, file=output_file('t_th_'//shock//'.dat'))
      write(iu,'(2es17.8e3)') (theta(l), t_th(l), l=1,m_theta)
      close(iu)

      open(newunit=iu, file=output_file('t_conv_'//shock//'.dat'))
      write(iu,'(2es17.8e3)') (theta(l), t_adv(l), l=1,m_theta)
      close(iu)

      open(newunit=iu, file=output_file('rad_adi_'//system//'_'//shock//'.dat'))
      write(iu,'(2es17.8e3)') (theta(l), t_th(l)/t_adv(l), l=1,m_theta)
      close(iu)

      ! In a radiative shock the hot layer must cool before being advected (t_th < t_adv),
      ! otherwise H_IL can become negative (see Martinez et al. 2023, Eq. 12)
      if (radiative) then
         n_adi = count(t_th(2:m_theta) > t_adv(2:m_theta))
         if (n_adi > 0) then
            l = findloc(t_th(2:m_theta) > t_adv(2:m_theta), .true., dim=1) + 1
            write(*,'(A,I4,A,F6.1,A)') ' WARNING (CD_termo): t_th > t_adv in ', n_adi, &
               ' cells of the '//shock//' (first at theta =', theta(l)*180./pi, &
               ' deg): the shock is adiabatic there'
         end if
      end if

      !-----------------------------------------------------------------
      ! Temperature and density of the isothermal layer

      if (radiative) then
         ! Temperature reached by the shocked gas after cooling during the advection
         ! time, between the photoionization temperature T_ion and the post-shock T
         ! (at the apex t_adv(1) ~ infinite: use t_adv(2))
         t_ratio = t_th/t_adv
         t_ratio(1) = t_th(1)/t_adv(2)
         T_IL = min( T, max(t_ratio*T, T_ion) )
         rho_IL = rho*(T/T_IL)                ! pressure equilibrium with the HL

         open(newunit=iu, file=output_file('T_IL_'//shock//'.dat'))
         write(iu,'(2es17.8e3)') (theta(l), T_IL(l), l=1,m_theta)
         close(iu)
      end if

      !-----------------------------------------------------------------
      ! Shock width from mass conservation

      y_eff = y*R0
      if (radiative) H_1 = (v_perp/r)*t_th      ! Post shock (hot) layer of a radiative shock

      ! Mass flux through the shock, accumulated from the apex
      dM = rho_med*v_perp * 2.d0*pi*R_theta*sin(theta)*dR
      dot_M = [( sum(dM(1:l)), l=1,m_theta )]

      if (radiative) then
         H_theta = dot_M/(2.d0*pi*y_eff*v_t*rho_IL) - H_1*rho/rho_IL
      else
         H_theta = dot_M/(2.d0*pi*y_eff*rho*v_t)    ! dot_M = 2*pi*y_eff*H*rho*v_t
      end if

      ! For theta < theta_min the approximation is not good: use the value at theta_min
      theta_min = 0.1d0
      l_min = int( (theta_min/theta_max) * m_theta )
      H_theta(1:l_min) = H_theta(l_min)

      dV_ring = 2.d0*pi*R_theta*sin(theta)*dR*H_theta    ! Volume of the ring

      open(newunit=iu, file=output_file('Hnorm_'//shock//'.dat'))
      if (radiative) then
         write(iu,'(6es17.8e3)') (theta(l), H_theta(l), R_acel(l)*R0, H_theta(l)/R_theta(l), &
                                  dV_ring(l), H_1(l), l=1,m_theta)
      else
         write(iu,'(5es17.8e3)') (theta(l), H_theta(l), R_acel(l)*R0, H_theta(l)/R_theta(l), &
                                  dV_ring(l), l=1,m_theta)
      end if
      close(iu)

      !-----------------------------------------------------------------
      ! Injected power available for the acceleration of NT particles:
      ! energy flux * area perpendicular to v_sh, in one quadrant
      ! (Eq. 14 from Martinez et al. 2022, Eq. 6 from Martinez et al. 2023)

      dA_perp = R_theta*sin(theta)*dR*(v_perp/v_sh)*d_phi
      e_flux = 0.5d0*rho_med*v_sh**2*v_perp                     ! supersonic region / radiative shock
      if (.not. radiative) e_flux(1:l_crit) = 0.5d0*rho_med(1:l_crit)*v_sh**3   ! subsonic region
      L_inj = e_flux*dA_perp
      L_inj_tot = sum(L_inj)
      L_cum = [( sum(L_inj(1:l)), l=1,m_theta )]

      open(newunit=iu, file=output_file('Linj_'//shock//'.dat'))
      write(iu,'(5es17.8e3)') (theta(l), r_norm(l), L_inj(l), dR(l)/R0, L_cum(l)*n_emit/L_sh, l=1,m_theta)
      close(iu)

      if (shock == 'RS') then
         write(*,80) 'L_inj_w =', L_sh
      end if
      write(*,80) 'L_inj('//shock//') =', L_inj_tot*n_emit ! It was just 1 quadrant
      write(*,80) 'L_NT_('//shock//') =',  frac_NT*(L_inj_tot*n_emit)
      write(*,81) 'L_NT/L_sh('//shock//') [%] =', frac_NT*(L_inj_tot*n_emit)/L_sh*100.d0
      if (shock == 'RS') then
         write(*,82) 'L_inj(RS)/L_w =', L_inj_tot*(n_emit)/L_sh
      else
         write(*,83) 'L_inj(FS)/L_ISM =', L_inj_tot*(n_emit)/L_sh
      end if

      !------------------------------
      ! Injection spectral index at the shocks (above E_break)

      allocate( alpha_sh(m_theta) )
      alpha_sh = 3._dp
      !alpha_sh = 2._dp
      !alpha_sh = 2.55_dp
      !alpha_sh = (r+2.d0)/(r-1.d0)
      open(newunit=iu, file=output_file('alpha_'//shock//'.dat'))
      write(iu,'(2es17.8e3)') (theta(l), alpha_sh(l), l=1,m_theta)
      close(iu)
      deallocate( alpha_sh )

      !------------------------------
      ! Write the results

      open(newunit=iu_termo, file=output_file('termo_'//shock//'.dat'))
      write(iu_termo,'(i6,11es17.8e3)') (l, rho(l), P(l), v_t(l), T(l), B(l), v_perp(l), theta(l), &
                                        Mach(l), r(l), rho_med(l), rho_IL(l), l=1,m_theta)
      close(iu_termo)

      open(newunit=iu_norm, file=output_file('termonorm_'//shock//'.dat'))  ! normalized
      write(iu_norm,'(9es17.8e3)') (theta(l), rho(l)/rho(1), P(l)/P(1), v_t(l)/v_sh, T(l)/T(1), &
                                    B(l)/B(1), v_perp(l)/v_sh, C_s_sh(l)/v_sh, rho_IL(l)/rho_IL(1), l=1,m_theta)
      close(iu_norm)

      open(newunit=iu_cmp, file=output_file('new_vs_RH_'//shock//'.dat'))   ! P, rho and v_t: new vs RH
      write(iu_cmp,'(4es17.8e3)') (theta(l), v_t(l)/v_t_RH(l), P(l)/P_RH(l), rho(l)/rho_RH(l), l=1,m_theta)
      close(iu_cmp)

      open(newunit=iu_H, file=output_file('H_'//shock//'.dat'))
      if (radiative) then
         write(iu_H,'(4es17.8e3)') (theta(l), H_theta(l), H_theta(l)/R_theta(l), H_1(l)/R_theta(l), l=1,m_theta)
      else
         write(iu_H,'(3es17.8e3)') (theta(l), H_theta(l), H_theta(l)/R_theta(l), l=1,m_theta)
      end if
      close(iu_H)

      if (radiative) then
         open(newunit=iu, file=output_file('termo_radiative_norm.dat'))
         write(iu,'(4es17.8e3)') (theta(l), rho(l)/rho_med(l), rho_IL(l)/rho_med(l), T(l)/T_ISM, l=1,m_theta)
         close(iu)
      end if

      print *, 'At the stagnation point (sw):'
      write(*,41) 'R0[pc] =',R0/pc
      write(*,41) 'R0/Rst =', R0/R_st
      if (shock == 'RS') then
         write(*,41) 'rho0/rho_w =',rho(1)/(Mdot/(4.d0*pi*R0**2*v_w))
         write(*,41) 'n_a0 =',rho(1)/mp/mu
      else
         write(*,41) 'rho0/rho_ISM =',rho(1)/rho_ISM
         write(*,41) 'n_a0 =',rho(1)/mp/mu
      end if
      write(*,41) 'P0 =',P(1)
      write(*,41) 'v0_t =',v_t(1)
      write(*,41) 'T0 =',T(1)
      write(*,41) 'B0 =',B(1)
      write(*,41) 'Beq0 =',sqrt(8.d0*pi*P(1))
      write(*,41) 'B_st <',(B(1)/4.d0)*(R0/R_st)*(v_w/v_st_rot)*r_A_st
      41  format (A12,ES9.2)

      deallocate( P,rho,T,B,v_t,v_perp,Mach,r,rho_med,C_s_med,C_s_sh,C_s_sh_new,rho_min,rho_IL )
      deallocate( H_1,H_theta )
      deallocate( x, y, y_eff )
      deallocate( v_t_new, P_new, rho_new, B_new)
      deallocate( v_t_RH, P_RH, rho_RH, B_RH )
      deallocate( dR, dV_ring, R_acel, L_inj, L_cum, e_flux, dA_perp, dM, dot_M )
      deallocate( v_A_new, v_ARH, V_A, lambda_tot, t_th, t_adv, t_ratio, T_IL, T_RH, T_new )

